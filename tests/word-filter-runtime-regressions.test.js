"use strict";
const assert=require("assert"),fs=require("fs"),path=require("path");
const {compile,match,diagnose}=require("../shared/word-filter-engine");
const root=path.resolve(__dirname,"..");
const discord=fs.readFileSync(path.join(root,"discord-app/discord-server.js"),"utf8");
const pg=fs.readFileSync(path.join(root,"shared/pg-sync-store.js"),"utf8");
const ui=fs.readFileSync(path.join(root,"public/app.js"),"utf8");
const c=compile({terms:[{term_id:"a",term:"arsch",category_id:"beleidigungen",severity:2,detection_type:"whole_word",enabled:true,leetspeak:true,platforms:[{platform:"discord",enabled:true}]}],allowlist:[]});
assert(match(c,"discord","4rsch"),"4rsch muss bei aktiviertem Leetspeak erkannt werden");
const d=compile({terms:[{term_id:"b",term:"bumsen",category_id:"beleidigungen",severity:2,detection_type:"whole_word",enabled:true,leetspeak:true,platforms:[{platform:"discord",enabled:true}]}],allowlist:[]});
assert(match(d,"discord","bum$en"),"bum$en muss bei aktiviertem Leetspeak erkannt werden");
const noLeet=compile({terms:[{term_id:"c",term:"arsch",category_id:"beleidigungen",severity:2,detection_type:"whole_word",enabled:true,leetspeak:false,platforms:[{platform:"discord",enabled:true}]}],allowlist:[]});
assert(!match(noLeet,"discord","4rsch"));
assert(diagnose(noLeet,"discord","4rsch").some(x=>x.reason==="leetspeak_disabled"),"Testlabor-Diagnose für deaktiviertes Leetspeak fehlt");
assert(discord.includes('claimModerationMessage(message.id)'),"Discord Message-Deduplizierung fehlt");
assert(discord.includes('applyWordFilterEscalation(message,fakeRule.name,hit.term.term,actions,null)'),"Zentrale Eskalation darf keinen zweiten Hinweis senden");
assert(discord.includes('if(!moderationChecks().manageMessages)throw new Error("Nachricht sollte gelöscht werden'),"Löschberechtigung wird nicht geprüft");
assert(pg.includes('message_template text'),"Policy-Hinweistext fehlt im Schema");
assert(ui.includes('data-policy-message-category'),"Hinweistext-Editor fehlt");
assert(ui.includes('1 niedrig · 2 auffällig · 3 deutlich · 4 schwer · 5 kritisch'),"Schweregrad-Legende fehlt");
console.log("word-filter-runtime-regressions.test.js: OK");

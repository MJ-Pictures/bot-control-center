const appSource=require("./helpers/app-source");
"use strict";
const assert=require("assert"),fs=require("fs"),path=require("path");
const engine=require("../shared/word-filter-engine");
const root=path.resolve(__dirname,"..");
const app=appSource();
const discord=fs.readFileSync(path.join(root,"discord-app/discord-server.js"),"utf8");
const ui=fs.readFileSync(path.join(root,"public/app.js"),"utf8");
const compiled=engine.compile({revision:1,terms:[{term_id:"a",term:"arsch",category_id:"beleidigungen",severity:2,detection_type:"whole_word",enabled:true,leetspeak:false,repeat_letters:false,flex_separators:false,platforms:[{platform:"discord",enabled:true}]}],allowlist:[],policies:[]});
assert.strictEqual(engine.match(compiled,"discord","4rsch"),null);
assert(engine.diagnose(compiled,"discord","4rsch").some(x=>x.reason==="leetspeak_disabled"));
assert(app.includes("wordFilterCentralReady"),"Twitch: zentrale Source-of-Truth-Markierung fehlt");
assert(app.includes("if(wordFilterOnTwitch && !wordFilterCentralReady() && !centralWordFilterMatched"),"Twitch: Legacy-Fallback läuft noch parallel");
assert(discord.includes("if(wordFilterOnDiscord && !wordFilterCentralReady && !centralWordFilterMatched"),"Discord: Legacy-Fallback läuft noch parallel");
assert(discord.includes("claimModerationMessage(message.id)"),"Discord: atomare Message-Claim-Deduplizierung fehlt");
assert(discord.includes("actions,null"),"Discord: Eskalation kann weiterhin Doppelwarnung erzeugen");
assert(ui.includes("Aktionsquelle:"),"Testlabor zeigt Aktionsquelle nicht");
assert(ui.includes("Ausführungsplan:"),"Testlabor zeigt Ausführungsplan nicht");
assert(ui.includes("Legacy-Fallback:"),"Testlabor zeigt Legacy-Pfad nicht");
assert(ui.includes("<span>Wirkung</span>"),"Wortbestand zeigt effektive Wirkung nicht");
console.log("word-filter-stability-v8011.test.js: OK");
